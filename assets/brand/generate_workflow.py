"""Generate the bilingual README workflow illustrations with only the stdlib."""

from __future__ import annotations

import argparse
from html import escape
from pathlib import Path

ASSETS = Path(__file__).resolve().parent.parent
LANGUAGES = {
    "en": (
        "How ClawBench works",
        (
            "Choose an everyday task, prepare a local or remote browser runtime, "
            "run an agent on the live website, and capture five layers of evidence "
            "to evaluate task success."
        ),
        (
            ("TASK", "Choose a task", "An everyday scenario", "on a live website."),
            ("RUNTIME", "Prepare runtime", "Local container or", "remote browser."),
            ("AGENT", "Run the agent", "Navigate, fill forms,", "and take actions."),
            (
                "EVIDENCE",
                "Record & score",
                "Capture five layers;",
                "evaluate task success.",
            ),
        ),
    ),
    "zh": (
        "ClawBench 工作流程",
        "选择日常任务，准备本地或远程浏览器环境，运行智能体，并记录五层数据来评测任务完成情况。",
        (
            ("任务", "选择任务", "真实网站上的", "日常在线任务。"),
            ("运行时", "准备环境", "使用本地容器", "或远程浏览器。"),
            ("智能体", "运行智能体", "导航、填写表单", "并执行操作。"),
            ("评测数据", "记录与评分", "记录五层数据，", "评测任务完成情况。"),
        ),
    ),
}
THEMES = {
    "light": ("#FFFCF8", "#DFE2E6", "#20242C", "#5C6571", "#C3CAD3", "#B84A34"),
    "dark": ("#151B25", "#34404F", "#F3F1ED", "#B6BEC9", "#607082", "#FC9C84"),
}
ICONS = (
    (
        '<rect x="27" y="54" width="45" height="48" rx="7"/>'
        '<path d="M39 51h20v8H39zM38 74h18m-18 10h24m-24 10h14"/>'
    ),
    (
        '<rect x="23" y="53" width="56" height="44" rx="7"/>'
        '<path d="M23 65h56m-43-6h1m6 0h1m6 0h1M36 77l6 5-6 5m13 0h14"/>'
    ),
    '<path d="M32 53v43l13-13 10 22 9-5-10-21h18ZM68 52l6-7m4 23h10M48 49V42"/>',
    '<path d="m23 68 28-16 28 16-28 16Zm0 13 28 16 28-16m-56 14 28 16 28-16"/>',
)


def text(value: str, x: int, y: int, size: float, weight: int, color: str) -> str:
    return (
        f'<text x="{x}" y="{y}" font-size="{size}" '
        f'font-weight="{weight}" fill="{color}">{escape(value)}</text>'
    )


def workflow_svg(language: str, theme: str, mobile: bool) -> str:
    title, description, stages = LANGUAGES[language]
    background, border, ink, muted, connector, number = THEMES[theme]
    width, height = (460, 480) if mobile else (960, 224)
    positions = (
        ((8, 8), (250, 8), (8, 256), (250, 256))
        if mobile
        else ((8, 8), (250, 8), (492, 8), (734, 8))
    )
    card_width, card_height = (202, 216) if mobile else (218, 204)
    pieces = [
        (
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
            f'viewBox="0 0 {width} {height}" '
            'font-family="system-ui, -apple-system, BlinkMacSystemFont, Segoe UI, sans-serif" '
            'role="img" aria-labelledby="title desc">'
        ),
        "<!-- Generated by assets/brand/generate_workflow.py; edit its source. -->",
        f'<title id="title">{escape(title)}</title>',
        f'<desc id="desc">{escape(description)}</desc>',
    ]
    for index, (stage, position, icon) in enumerate(
        zip(stages, positions, ICONS, strict=True)
    ):
        label, heading, line1, line2 = stage
        x, y = position
        pieces.extend(
            (
                f'<g transform="translate({x} {y})">',
                (
                    f'<rect width="{card_width}" height="{card_height}" rx="16" '
                    f'fill="{background}" stroke="{border}"/>'
                ),
                text(f"0{index + 1}", 22, 32, 14 if mobile else 12, 750, number),
                text(label, 49, 32, 12 if mobile else 10, 650, muted),
                '<g fill="none" stroke="#EB6449" stroke-width="2.5" '
                'stroke-linecap="round" stroke-linejoin="round">' + icon + "</g>",
                text(
                    heading, 22, 138 if mobile else 136, 19 if mobile else 17, 750, ink
                ),
                text(
                    line1,
                    22,
                    170 if mobile else 161,
                    16 if mobile else 12.5,
                    500,
                    muted,
                ),
                text(
                    line2,
                    22,
                    194 if mobile else 180,
                    16 if mobile else 12.5,
                    500,
                    muted,
                ),
                "</g>",
            )
        )
    arrows = (
        "M216 116h26m-5-5 5 5-5 5M216 364h26m-5-5 5 5-5 5"
        "M350 230v10H110v10m-5-5 5 5 5-5"
        if mobile
        else "M232 110h12m-5-5 5 5-5 5M474 110h12m-5-5 5 5-5 5M716 110h12m-5-5 5 5-5 5"
    )
    pieces.extend(
        (
            (
                f'<path d="{arrows}" fill="none" stroke="{connector}" stroke-width="2" '
                'stroke-linecap="round" stroke-linejoin="round"/>'
            ),
            "</svg>\n",
        )
    )
    return "\n".join(pieces)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Report outdated SVGs without writing them.",
    )
    args = parser.parse_args()
    outdated = []
    for language in LANGUAGES:
        for theme in THEMES:
            for mobile in (False, True):
                filename = (
                    f"workflow-{'zh-' if language == 'zh' else ''}"
                    f"{'mobile-' if mobile else ''}{theme}.svg"
                )
                path = ASSETS / filename
                contents = workflow_svg(language, theme, mobile)
                if args.check:
                    if (
                        not path.exists()
                        or path.read_text(encoding="utf-8") != contents
                    ):
                        outdated.append(filename)
                else:
                    path.write_text(contents, encoding="utf-8")
    if outdated:
        print("Outdated workflow SVGs: " + ", ".join(outdated))
        return 1
    print(
        "All 8 workflow SVGs are current."
        if args.check
        else "Generated 8 workflow SVGs."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
